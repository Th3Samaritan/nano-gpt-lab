"""Layman-facing visualizations.

WHAT
----
Every figure here is designed so a NON-engineer can read it in 5 seconds:
    - one idea per chart
    - plain-English titles ("Which recipe learned the language best?")
    - explicit hints on the chart ("lower = better", "higher = faster")
    - concept cartoons for attention / RoPE / FlashAttention / BPE that
      show WHAT is computed, not formulas

WHY
----
The research goal is answering "WHY did the number change?" - and the
evidence only persuades if people who cannot read the code can read the
result. These charts are the lab's external interface.

WHERE
-----
Generated by the trainer (loss curves), by scripts/analyze.py (comparison
suite) and by notebooks/04_experiment_analysis.ipynb. All outputs are
PNG files saved next to the data they describe.
"""
from __future__ import annotations

import os
from typing import Dict, List, Optional

import matplotlib
matplotlib.use("Agg")  # headless-safe everywhere (Colab/Kaggle/local)
import matplotlib.pyplot as plt
import numpy as np

# Colorblind-friendly palette, fixed so charts are comparable across runs.
PALETTE = {
    "vanilla_learned": "#0072B2",   # blue   - A: classic + position table
    "vanilla_rope": "#D55E00",      # orange - B: classic + rotation
    "flash_learned": "#009E73",     # green  - C: flash + position table
    "flash_rope": "#CC79A7",        # purple - D: flash + rotation
}
VARIANT_LABELS = {
    "vanilla_learned": "A: Classic attention\n+ position table",
    "vanilla_rope": "B: Classic attention\n+ rotation (RoPE)",
    "flash_learned": "C: Flash attention\n+ position table",
    "flash_rope": "D: Flash attention\n+ rotation (RoPE)",
}
VARIANT_SHORT = {
    "vanilla_learned": "A", "vanilla_rope": "B",
    "flash_learned": "C", "flash_rope": "D",
}
_BIG = 16
_MED = 12


def _variant_key(entry: dict) -> str:
    # Normalize attention: the A/B/C/D labels treat flash_tiled and
    # flash_fused as the same experimental CELL (flash attention) - they
    # differ only in implementation, not in the ablation variable.
    attn = entry["attention"]
    if attn.startswith("flash"):
        attn = "flash"
    return f"{attn}_{entry['position']}"


def _color_of(key: str) -> str:
    return PALETTE.get(key, "#777777")


def _label_of(key: str) -> str:
    return VARIANT_LABELS.get(key, key.replace("_", " + "))


def _save(fig, path: str) -> str:
    os.makedirs(os.path.dirname(path), exist_ok=True)
    fig.savefig(path, dpi=150, bbox_inches="tight", facecolor="white")
    plt.close(fig)
    return path


# --------------------------------------------------------------------------
# 1. Loss curves - the basic training progress picture
# --------------------------------------------------------------------------
def plot_loss_curves_layman(run_dir: str, out_path: Optional[str] = None) -> Optional[str]:
    """Train/val loss vs tokens with plain-English annotations."""
    csv_path = os.path.join(run_dir, "metrics.csv")
    if not os.path.exists(csv_path):
        return None
    import csv
    tokens, train_l, val_l = [], [], []
    with open(csv_path, newline="", encoding="utf-8") as f:
        for row in csv.DictReader(f):
            try:
                tokens.append(int(row["tokens_seen"]))
                train_l.append(float(row["train_loss"]))
                val_l.append(float(row["val_loss"]))
            except (ValueError, KeyError):
                continue
    if not tokens:
        return None
    if out_path is None:
        out_path = os.path.join(run_dir, "learning_progress.png")
    fig, ax = plt.subplots(figsize=(9, 5.5))
    ax.plot(tokens, train_l, color="#0072B2", lw=2.5,
            label="learning curve (training)")
    ax.plot(tokens, val_l, color="#D55E00", lw=2.5,
            label="checkup curve (unseen text)")
    ax.set_xlabel("amount of text read (tokens)", fontsize=_MED)
    ax.set_ylabel("mistake level (loss)", fontsize=_MED)
    ax.set_title("The model makes fewer mistakes as it reads more text",
                 fontsize=_BIG, pad=12)
    ax.annotate("lower = better", xy=(0.98, 0.9), xycoords="axes fraction",
                ha="right", fontsize=_MED, color="#555555")
    ax.legend(fontsize=_MED, frameon=False)
    ax.grid(alpha=0.25)
    ax.set_ylim(0, None)
    fig.tight_layout()
    return _save(fig, out_path)


