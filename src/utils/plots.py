# 2. Concept cartoons - one idea each
# --------------------------------------------------------------------------
def plot_attention_concept(out_path: str) -> str:
    """WHAT attention does, in three panels, no formulas.

    Panel 1: compare - score how useful each EARLIER word is for now.
    Panel 2: normalize - turn scores into percentages (softmax).
    Panel 3: gather - blend earlier words' meanings by those percentages.
    """
    fig, axes = plt.subplots(1, 3, figsize=(15, 4.6))
    words = ["The", "cat", "sat", "on", "the", "mat"]
    n = len(words)
    for ax, title, sub in zip(
            axes,
            ["1. COMPARE", "2. TURN INTO %", "3. GATHER"],
            ["How useful is each\nearlier word for\nreading the next one?",
             "Convert the scores into\npercentages that add up\nto 100%.",
             "Blend the earlier words'\nmeanings by those\npercentages."]):
        ax.set_xlim(-0.5, n - 0.5)
        ax.set_ylim(0, 1)
        ax.axis("off")
        ax.set_title(title, fontsize=_BIG, color="#0072B2")
        if title.startswith("1."):
            heights = np.linspace(0.15, 0.9, n)
            for i, (w, h) in enumerate(zip(words, heights)):
                ax.bar(i, h, color="#66A6CC", alpha=0.9)
                ax.text(i, h + 0.05, f"{h:.0%}", ha="center", fontsize=10)
        elif title.startswith("2."):
            vals = np.linspace(0.05, 0.45, n)
            vals = vals / vals.sum()
            for i, (w, v) in enumerate(zip(words, vals)):
                ax.bar(i, v, color="#D55E00", alpha=0.9)
                ax.text(i, v + 0.05, f"{v:.0%}", ha="center", fontsize=10)
        else:
            sizes = np.linspace(400, 1200, n)
            for i, (w, s) in enumerate(zip(words, sizes)):
                ax.scatter([i], [0.5], s=s, color="#009E73", alpha=0.85)
                ax.text(i, 0.5, w, ha="center", va="center", fontsize=10,
                        color="white")
            ax.text(n - 0.5, 0.9, "size = share of\nattention", ha="center",
                    fontsize=10, color="#009E73")
        for i, w in enumerate(words):
            ax.text(i, -0.02, w, ha="center", fontsize=11)
        ax.text(0, -0.16, sub, ha="left", fontsize=_MED, color="#333333")
    fig.suptitle("How attention works: every word looks back, scores its "
                 "neighbours, and blends their meanings",
                 fontsize=17, y=1.02)
    return _save(fig, out_path)


def plot_rope_concept(out_path: str) -> str:
    """RoPE cartoon: position = rotation angle.

    Left: one token's arrow rotated differently for each position in the
    sentence. Right: two arrows whose angle difference stays the SAME for
    the same distance apart - that constant difference is how the model
    "sees" relative position.
    """
    fig, axes = plt.subplots(1, 2, figsize=(12.5, 5))
    # Left: absolute rotation grows with position
    ax = axes[0]
    ax.set_xlim(-1.2, 1.2); ax.set_ylim(-1.2, 1.2)
    ax.axhline(0, color="grey", lw=0.5); ax.axvline(0, color="grey", lw=0.5)
    for pos in range(6):
        ang = pos * 0.55
        x, y = np.cos(ang), np.sin(ang)
        ax.arrow(0, 0, x, y, head_width=0.06, head_length=0.08,
                 fc=PALETTE["vanilla_rope"], ec=PALETTE["vanilla_rope"],
                 lw=2, length_includes_head=True)
        ax.text(x * 1.22, y * 1.22, f"word {pos}", fontsize=11, ha="center",
                color="#D55E00")
    ax.set_title("Each position = a different\nrotation of the same arrow",
                 fontsize=_BIG, color="#D55E00")
    ax.set_aspect("equal"); ax.axis("off")
    # Right: relative angle is constant for the same distance
    ax = axes[1]
    ax.set_xlim(-1.2, 1.2); ax.set_ylim(-1.2, 1.2)
    ax.axhline(0, color="grey", lw=0.5); ax.axvline(0, color="grey", lw=0.5)
    for pos, col in [(2, "#0072B2"), (5, "#D55E00")]:
        ang = pos * 0.55
        ax.arrow(0, 0, np.cos(ang), np.sin(ang), head_width=0.06,
                 head_length=0.08, fc=col, ec=col, lw=2.5,
                 length_includes_head=True)
        ax.text(np.cos(ang) * 1.2, np.sin(ang) * 1.2,
                f"word {pos}", fontsize=11, ha="center", color=col)
    arc = plt.Arc((0, 0), 0.7, 0.7, angle=0, theta1=0, theta2=150,
                  color="#555555", lw=1.5, linestyle="--")
    ax.add_patch(arc)
    ax.text(0.55, 0.55, "same angle gap\n= same distance\napart", fontsize=11,
            ha="center", color="#555555")
    ax.set_title("Words the same distance apart\nalways see the same angle gap",
                 fontsize=_BIG, color="#0072B2")
    ax.set_aspect("equal"); ax.axis("off")
    fig.suptitle("Rotation positions (RoPE): where a word sits = how far its "
                 "meaning-arrow is turned", fontsize=17, y=1.02)
    return _save(fig, out_path)


def plot_flash_concept(out_path: str) -> str:
    """FlashAttention cartoon: giant score table vs one strip at a time.

    Left: the classic method materializes the FULL T x T comparison table
    (red, expensive). Right: flash works strip by strip, keeping only one
    strip in memory and updating a running result (green, cheap). Same
    final answer - the strip method is algebraically exact.
    """
    fig, axes = plt.subplots(1, 2, figsize=(12.5, 5.2))
    T = 10
    grid = np.ones((T, T))
    ax = axes[0]
    ax.imshow(grid, cmap="Reds", vmin=0, vmax=1, interpolation="nearest")
    ax.set_xticks([]); ax.set_yticks([])
    ax.set_xlabel("words so far", fontsize=_MED)
    ax.set_ylabel("current word", fontsize=_MED)
    ax.set_title("Classic attention: builds the\nWHOLE comparison table at once",
                 fontsize=_BIG, color="#8B0000")
    ax.text(0.5, -0.16, "10 x 10 = 100 boxes to remember", transform=ax.transAxes,
            ha="center", fontsize=_MED, color="#8B0000")
    ax = axes[1]
    ax.imshow(np.tril(np.ones((T, T))), cmap="Greens", vmin=0, vmax=1,
              interpolation="nearest")
    for j in range(T):
        ax.axvline(j + 0.5, color="white", lw=2.5)
    ax.axvspan(2.5, 3.5, color="#CC79A7", alpha=0.55)
    ax.set_xticks([]); ax.set_yticks([])
    ax.set_xlabel("words so far", fontsize=_MED)
    ax.set_ylabel("current word", fontsize=_MED)
    ax.set_title("Flash attention: works through\nONE strip at a time",
                 fontsize=_BIG, color="#006400")
    ax.text(0.5, -0.16, "only 1 strip in memory at any moment",
            transform=ax.transAxes, ha="center", fontsize=_MED,
            color="#006400")
    ax.text(3, -1.6, "in use now", ha="center", fontsize=10, color="#CC79A7")
    fig.suptitle("FlashAttention: same final answer, far less memory - the "
                 "table is processed strip by strip", fontsize=17, y=1.02)
    return _save(fig, out_path)


def plot_bpe_concept(text: str, tokenizer, out_path: str) -> str:
    """BPE cartoon: how a sentence is chopped into reusable pieces.

    Each token is drawn as a coloured box; frequent words become ONE box,
    rare words get split into several smaller (still reusable) pieces.
    Caption states the compression: N characters -> M pieces.
    """
    ids = tokenizer.encode(text)
    pieces = [tokenizer.decode([i]) for i in ids]
    fig, ax = plt.subplots(figsize=(max(8, len(pieces) * 0.55), 3.6))
    ax.axis("off")
    x = 0.0
    cmap = plt.get_cmap("tab20")
    for k, piece in enumerate(pieces):
        w = max(0.32, len(piece) * 0.16)
        ax.add_patch(plt.Rectangle((x, 0.3), w - 0.03, 0.6,
                                   facecolor=cmap(k % 20), alpha=0.85,
                                   edgecolor="black"))
        ax.text(x + (w - 0.03) / 2, 0.6, piece.replace(" ", "␣"),
                ha="center", va="center", fontsize=10)
        x += w
    ax.set_xlim(0, x)
    ax.set_ylim(0, 1.1)
    ratio = len(text) / max(len(ids), 1)
    ax.text(0, -0.12,
            f"{len(text)} characters -> {len(ids)} reusable pieces "
            f"(each piece ~{ratio:.1f} characters)",
            fontsize=_MED, color="#333333")
    ax.set_title("How the tokenizer chops text into reusable pieces (BPE)",
                 fontsize=_BIG)
    return _save(fig, out_path)


